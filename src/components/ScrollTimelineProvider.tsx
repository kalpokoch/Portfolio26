import {
  createContext,
  useContext,
  useEffect,
  useRef,
  type ReactNode,
  type RefObject,
} from "react";
import { createLenis, ScrollTrigger } from "../lib/smooth-scroll";
import {
  SCENES,
  SCENE_RANGES,
  TOTAL_WEIGHT,
  activeSceneIndex,
  sceneLocalProgress,
  sceneSettledProgress,
} from "../lib/scene-registry";
import { timelineStore } from "../store/timeline-store";
import { useReducedMotion } from "../lib/use-reduced-motion";
import { useIsMobile } from "../lib/use-is-mobile";
import { measureDeviceTier } from "../lib/device-tier";

interface TimelineContextValue {
  trackRef: RefObject<HTMLDivElement | null>;
  scrollToScene: (index: number) => void;
}

const TimelineContext = createContext<TimelineContextValue | null>(null);

export function useTimeline(): TimelineContextValue {
  const ctx = useContext(TimelineContext);
  if (!ctx) throw new Error("useTimeline must be used within ScrollTimelineProvider");
  return ctx;
}

// How long scrolling must be idle before we ease the rest of the way into the nearest
// chapter's fully-settled view — long enough to not fight normal wheel-notch scrolling,
// short enough to feel responsive once the user actually stops.
const SNAP_IDLE_MS = 180;
const SNAP_THRESHOLD = 0.002;

function easeOutCubic(t: number): number {
  return 1 - Math.pow(1 - t, 3);
}

export function ScrollTimelineProvider({ children }: { children: ReactNode }) {
  const reducedMotion = useReducedMotion();
  const isMobile = useIsMobile();
  const trackRef = useRef<HTMLDivElement | null>(null);
  const lenisRef = useRef<ReturnType<typeof createLenis>["lenis"] | null>(null);
  const stRef = useRef<ScrollTrigger | null>(null);
  const idleTimerRef = useRef<number | null>(null);

  useEffect(() => {
    timelineStore.getState().setReducedMotion(reducedMotion);
  }, [reducedMotion]);

  useEffect(() => measureDeviceTier((tier) => timelineStore.getState().setDeviceTier(tier)), []);

  useEffect(() => {
    if (reducedMotion || isMobile || !trackRef.current) return;

    const { lenis, destroy } = createLenis();
    lenisRef.current = lenis;

    const st = ScrollTrigger.create({
      trigger: trackRef.current,
      start: "top top",
      end: () => `+=${window.innerHeight * TOTAL_WEIGHT}`,
      pin: true,
      scrub: 1,
      onUpdate: (self) => {
        timelineStore.getState().setProgress(self.progress);
        timelineStore.getState().setActiveSceneIndex(activeSceneIndex(self.progress));

        // Debounced auto-snap: every scroll tick pushes this back, including the ticks
        // generated by the snap animation itself, so it only fires once motion truly stops —
        // guaranteeing scroll never rests permanently mid cross-fade between two chapters.
        if (idleTimerRef.current !== null) window.clearTimeout(idleTimerRef.current);
        idleTimerRef.current = window.setTimeout(() => {
          const current = timelineStore.getState().progress;
          const idx = activeSceneIndex(current);
          const local = sceneLocalProgress(current, SCENES[idx].id);
          const settled = sceneSettledProgress(idx, local);
          if (Math.abs(current - settled) < SNAP_THRESHOLD) return;
          const target = self.start + settled * (self.end - self.start);
          lenisRef.current?.scrollTo(target, { duration: 0.5, easing: easeOutCubic });
        }, SNAP_IDLE_MS);
      },
    });
    stRef.current = st;

    return () => {
      if (idleTimerRef.current !== null) window.clearTimeout(idleTimerRef.current);
      st.kill();
      destroy();
      lenisRef.current = null;
      stRef.current = null;
    };
  }, [reducedMotion, isMobile]);

  const scrollToScene = (index: number) => {
    const range = SCENE_RANGES[index];
    if (!range) return;
    const st = stRef.current;
    if (st && lenisRef.current) {
      const settled = sceneSettledProgress(index);
      const target = st.start + settled * (st.end - st.start);
      lenisRef.current.scrollTo(target, { duration: 1.2 });
      return;
    }
    document
      .getElementById(`scene-${range.id}`)
      ?.scrollIntoView({ behavior: "smooth", block: "start" });
  };

  return (
    <TimelineContext.Provider value={{ trackRef, scrollToScene }}>
      {children}
    </TimelineContext.Provider>
  );
}
